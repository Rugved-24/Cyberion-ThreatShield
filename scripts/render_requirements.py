"""Render PROJECT_REQUIREMENTS.md and the machine-readable requirements matrix.

The matrix itself lives in scripts/requirements_matrix.py so that it is data
rather than prose. This script renders it into the human-readable document and
the machine-readable CSV and JSON, so the three views cannot disagree.

    python scripts/render_requirements.py
"""

import csv
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from requirements_matrix import LIMITATIONS, PRD_ID, PRD_VERSION, REQUIREMENTS

ROOT = Path(__file__).resolve().parents[1]


def render():
    now = datetime.now(UTC).date().isoformat()
    mandatory = [r for r in REQUIREMENTS if not r.get("optional")]
    optional = [r for r in REQUIREMENTS if r.get("optional")]
    lines = [
        "# Project Requirements and Completion Checklist", "",
        f"Controlling specification: **{PRD_ID} version {PRD_VERSION}**, Cyberion Defense Labs",
        "Detection Engineering and Threat Hunting Engagement.", "",
        f"Rendered: {now}. Generated by `scripts/render_requirements.py` from",
        "`scripts/requirements_matrix.py`. Do not hand-edit; edit the matrix and re-render.", "",
        "This file is the requirement-to-artefact traceability record. Every requirement",
        "carries the checks that `scripts/prd_compliance.py` must run against a real artefact.",
        "A requirement is not satisfied by a file existing.", "",
        "## How to read this document", "",
        "| Column | Meaning |", "| --- | --- |",
        "| ID | Stable requirement identifier, cited by every compliance report |",
        "| PRD | The PRD section the requirement comes from |",
        "| Requirement | The requirement in PRD terminology |",
        "| Artefacts | Files that must exist and be substantive |",
        "| Checks | Named verifications, run against content rather than filenames |",
        "| Status | Filled by the compliance audit |", "",
        "## Verification status", "",
        "The Status column is populated by `scripts/prd_compliance.py`, which writes",
        "`docs/prd-compliance-report.md`. The current result is summarised in",
        "`reports/final-status-report.md`.", "",
        "## Mandatory requirements", "",
        "| ID | PRD | Requirement | Artefacts | Checks |", "| --- | --- | --- | --- | --- |",
    ]
    for item in mandatory:
        artefacts = ", ".join(f"`{a}`" for a in item["artefacts"])
        checks = ", ".join(f"`{c}`" for c in item["verify"])
        text = item["text"].replace("|", "/")
        lines.append(f"| {item['id']} | {item['prd']} | {text} | {artefacts} | {checks} |")
    lines += ["", "## Optional enhancements, PRD section 11", "",
              "These are stretch goals. They never gate completion, and the compliance audit",
              "reports them separately so a missing one cannot be mistaken for a failure.", "",
              "| ID | Requirement | Artefacts | Checks |", "| --- | --- | --- | --- |"]
    for item in optional:
        artefacts = ", ".join(f"`{a}`" for a in item["artefacts"])
        checks = ", ".join(f"`{c}`" for c in item["verify"])
        lines.append(f"| {item['id']} | {item['text']} | {artefacts} | {checks} |")
    lines += ["", "## Recorded limitations", "",
              "Requirements this environment cannot legitimately satisfy. These are disclosed",
              "gaps, not incomplete work, and are never counted as failures. Each one states",
              "what was not done and why, so that a reviewer can see the boundary of the work.", ""]
    for item in LIMITATIONS:
        lines += [
            f"### {item['id']}", "",
            f"- **Requirement affected:** {item['requirement']}",
            f"- **What was asked:** {item['text']}",
            f"- **Effect on the requirement:** {item['effect']}",
            f"- **Why it cannot be satisfied here:** {item['reason']}",
            f"- **Evidence:** {item['evidence']}",
            f"- **What was deliberately not done:** {item['not_fabricated']}", "",
        ]
    lines += ["## Counts", "",
              f"- Mandatory requirements: **{len(mandatory)}**",
              f"- Optional enhancements: **{len(optional)}**",
              f"- Recorded limitations: **{len(LIMITATIONS)}**",
              f"- Total named checks: **{sum(len(r['verify']) for r in REQUIREMENTS)}**", ""]
    (ROOT / "PROJECT_REQUIREMENTS.md").write_text("\n".join(lines) + "\n",
                                                   encoding="utf-8", newline="\n")

    rows = [{"id": r["id"], "prd_section": r["prd"], "kind": r["kind"],
             "target": r.get("target", ""), "requirement": r["text"],
             "artefacts": ";".join(r["artefacts"]), "checks": ";".join(r["verify"]),
             "optional": bool(r.get("optional"))} for r in REQUIREMENTS]
    csv_path = ROOT / "PROJECT_REQUIREMENTS.csv"
    with csv_path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    (ROOT / "PROJECT_REQUIREMENTS.json").write_text(
        json.dumps({"prd": PRD_ID, "version": PRD_VERSION, "rendered": now,
                    "requirements": rows, "limitations": LIMITATIONS},
                   indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"mandatory {len(mandatory)} | optional {len(optional)} | limitations {len(LIMITATIONS)}")
    print("written: PROJECT_REQUIREMENTS.md, PROJECT_REQUIREMENTS.csv, PROJECT_REQUIREMENTS.json")


if __name__ == "__main__":
    render()
