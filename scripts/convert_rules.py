"""Convert the Sigma rule library to KQL and SPL to demonstrate portability.

This is the PRD section 11 optional enhancement "convert a subset of Sigma rules
to a second query language using a conversion tool". It uses the real tool,
sigma-cli with the kusto and splunk backends, not a hand translation.

Two things about the output matter for anyone deploying it and are recorded in
detections/converted/README.md rather than left for the reader to discover:

- a Sigma rule with custom `x-` blocks and a GUID-join correlation cannot be
  expressed in a single-event query language, and the converter refuses or drops
  it, so correlation rules are converted only where a faithful single-event
  translation exists;
- field names are backend-mapped, so an `Image` condition becomes a different
  column depending on the pipeline chosen.
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "detections" / "converted"
SIGMA = ROOT / ".venv/Scripts/sigma.exe"
TARGETS = [("kusto", "kql", None), ("splunk", "spl", "splunk_windows")]


def run(arguments):
    result = subprocess.run([str(SIGMA), *arguments], cwd=ROOT, capture_output=True,
                            text=True, timeout=180)
    return result.returncode, result.stdout, result.stderr


def main():
    if not SIGMA.exists():
        sys.exit(f"{SIGMA} not found")
    OUT.mkdir(parents=True, exist_ok=True)
    rules = sorted(path for path in (ROOT / "rules").rglob("*.yml")
                   if not path.name.startswith("_"))
    _, listing, _ = run(("list", "targets"))
    if "kusto" not in listing or "splunk" not in listing:
        sys.exit("Backends not installed. Run: sigma plugin install kusto splunk")
    report = []
    for rule in rules:
        text = rule.read_text(encoding="utf-8")
        correlation = "x-correlation:" in text
        label = rule.relative_to(ROOT).as_posix()
        if correlation:
            # Refused deliberately. The converter folds a parent selection and a
            # child selection into a single AND, which in a row-oriented query
            # language asks for one event that is both processes at once. That
            # query can never match, and shipping it would look like a working
            # conversion while being a silent semantic corruption. The GUID join
            # and the time window have no single-query equivalent.
            report.append({"rule": label, "target": "kusto", "converted": False,
                           "note": "refused: correlation logic has no single-query equivalent"})
            report.append({"rule": label, "target": "splunk", "converted": False,
                           "note": "refused: correlation logic has no single-query equivalent"})
            continue
        for target, suffix, pipeline in TARGETS:
            name = f"{rule.stem}.{suffix}"
            arguments = ["convert", "-t", target]
            if pipeline:
                arguments += ["-p", pipeline]
            arguments.append(str(rule))
            code, out, err = run(arguments)
            query = ""
            for line in out.splitlines():
                if "Parsing Sigma rules" in line:
                    continue
                if line.strip():
                    query = line.strip()
                    break
            if code == 0 and query:
                (OUT / name).write_text(query + "\n", encoding="utf-8", newline="\n")
                note = ""
            else:
                note = (err.strip().splitlines() or ["conversion refused"])[-1][:90]
            report.append({"rule": label, "target": target, "converted": bool(query),
                           "note": note})
    readme = f"""# Converted queries

Generated by `scripts/convert_rules.py` using sigma-cli 3.1.0 with the official
`kusto` and `splunk` backends. This is PRD section 11 optional enhancement
"convert a subset of Sigma rules to a second query language using a conversion
tool". The conversion is performed by the tool, not hand-written.

## What is here

{sum(1 for row in report if row['converted'])} converted queries from
{len({row['rule'] for row in report if row['converted']})} single-event Sigma rules
across two backends. Files are named `<rule stem>.kql` and `<rule stem>.spl`.

## The three correlation rules are deliberately absent, and why

This is the most important thing on this page.

CT-C01, CT-C02 and CT-C03 depend on a parent and a child process joined on a
process GUID within a time window. The converter handles this by folding the two
selections into a single `AND`. In a row-oriented query language that produces a
query asking for **one event that is both `cmd.exe` and `powershell.exe` at the
same time**, which can never match anything.

The converter does not report an error. It emits a syntactically valid query that
is silently, permanently wrong. Rather than publish three queries that look like
working detections and match nothing, the script refuses to convert correlation
rules and records the refusal.

A deployable equivalent needs a scheduled query, a join across two event
tables, or a native SIEM correlation search built separately. That is real work
and is not claimed here.

## What a reader must know before deploying these

1. **Field names are backend-mapped.** The same rule becomes different columns
   depending on the pipeline: the Splunk pipeline maps `EventID` to `EventCode`
   and turns `endswith` into a wildcard, while the bare Kusto backend keeps
   `EventID` and its native `endswith` and `contains` operators. A pipeline choice
   is a design decision, not a default.

2. **Conversion proves portability, not correctness.** The authoritative test
   remains `scripts/test_all.py`, which replays the Sigma condition against the
   recorded telemetry. No converted query has been executed against this data and
   no result is claimed for it.

3. **Custom `x-` blocks are dropped.** The ATT&CK mapping, severity rationale,
   scope, evidence list and benign review exist only in the Sigma file. A deployed
   query carries none of it, so the Sigma file must ship alongside it.

## Table

| Rule | KQL | SPL | Note |
| --- | --- | --- | --- |
""" + "\n".join(
        f"| {row['rule'].split('/')[-1]} | "
        f"{'yes' if row['target'] == 'kusto' and row['converted'] else 'no'} | "
        f"{'yes' if row['target'] == 'splunk' and row['converted'] else 'no'} | "
        f"{row['note'] or 'single-event rule'} |"
        for row in report) + "\n"
    (OUT / "README.md").write_text(readme, encoding="utf-8", newline="\n")
    ok = sum(1 for row in report if row["converted"])
    print(f"converted {ok} of {len(report)} conversions attempted across {len(rules)} rules")
    for row in report:
        if not row["converted"]:
            print(f"  refused: {row['rule']} -> {row['target']}: {row['note']}")
    print(f"written: {(OUT / 'README.md').relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
